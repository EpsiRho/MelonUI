import { writeFileSync } from 'node:fs';
import { controls } from '../content/controls.mjs';
const cases = controls.map(c => `("${c.slug}", () => Build_${c.slug}(sampleDirectory), ${JSON.stringify(c.mxml)}, page => { ${c.setup ?? ''} })`).join(',\n');
const methods = controls.map(c => `private static UIElement Build_${c.slug}(string sampleDirectory)\n{\n${c.code}\nreturn control;\n}`).join('\n\n');
writeFileSync(new URL('../examples/GeneratedSamples.cs', import.meta.url), `// Generated by scripts/prepare-examples.mjs; edit content/controls.mjs instead.
using System.Drawing;
using MelonUI.Base;
using MelonUI.Default;
using MelonUI.Enums;
namespace MelonUI.Docs;
internal static class Samples {
internal static (string Slug, Func<UIElement> Build, string Mxml, Action<MUIPage> Configure)[] All(string sampleDirectory) => [
${cases}
];
${methods}
}
`);
console.log(`Prepared ${controls.length} paired control examples.`);
